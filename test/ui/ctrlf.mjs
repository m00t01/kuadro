// Ctrl+F focuses the search box; typing filters; Esc clears, Esc again leaves the box.
import puppeteer from 'puppeteer-core';
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox', '--allow-file-access-from-files'] });
const p = await b.newPage(); await p.setViewport({ width: 1300, height: 860 });
const errs = []; p.on('pageerror', e => errs.push(e.message));
const wait = ms => new Promise(r => setTimeout(r, ms)), out = [], ok = (n, v) => out.push((v ? 'ok   ' : 'FAIL ') + n);
await p.goto('file:///home/claude/kuadro/dist/index.html'); await p.evaluate(() => localStorage.clear()); await p.reload(); await wait(400);
await p.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent.startsWith('Open demo')).click()); await wait(1800);
await p.click('.grid tbody td.title'); await wait(100);
const n0 = await p.evaluate(() => document.querySelectorAll('.grid tbody tr').length);
await p.keyboard.down('Control'); await p.keyboard.press('f'); await p.keyboard.up('Control'); await wait(150);
ok('Ctrl+F focuses search', await p.evaluate(() => document.activeElement && document.activeElement.classList.contains('search')));
await p.keyboard.type('jetpack'); await wait(300);
const n1 = await p.evaluate(() => document.querySelectorAll('.grid tbody tr').length);
ok('typing filters rows', n1 > 0 && n1 < n0 && await p.evaluate(() => [...document.querySelectorAll('.grid tbody tr')].every(tr => /jetpack/i.test(tr.textContent))));
await p.keyboard.press('Escape'); await wait(200);
ok('Esc clears', await p.evaluate(() => document.querySelector('.topbar input.search').value === '') && await p.evaluate(() => document.querySelectorAll('.grid tbody tr').length) === n0);
await p.keyboard.press('Escape'); await wait(100);
ok('Esc again leaves the box', await p.evaluate(() => !document.activeElement.classList.contains('search')));
console.log(out.join('\n')); console.log('errors:', errs); await b.close();
